// Builds the self-contained GitHub Pages folder playground/dist/:
//   node playground/build.mjs
// Copies the playground sources + js/*.mjs + js/*.wasm + default fonts into dist/ (vendor/) and writes a
// dist/config.js that points at ./vendor/. Nothing is rewritten at runtime.
import { mkdirSync, rmSync, copyFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const DIST = path.join(HERE, "dist");
rmSync(DIST, { recursive: true, force: true });
mkdirSync(path.join(DIST, "vendor", "fonts"), { recursive: true });

const cp = (from, to) => { copyFileSync(from, to); return statSync(to).size; };
let total = 0;
for (const f of ["index.html", "style.css", "app.js", "i18n.js", "templates.js", ".nojekyll"]) total += cp(path.join(HERE, f), path.join(DIST, f));
for (const f of readdirSync(path.join(ROOT, "js"))) {
  if (/\.(mjs|wasm)$/.test(f) && !/^node(-|\.)/.test(f)) total += cp(path.join(ROOT, "js", f), path.join(DIST, "vendor", f));
}
const FONTS = ["Inter-Regular.ttf", "Inter-SemiBold.ttf", "Inter-Bold.ttf", "Inter-Italic.ttf", "NotoSans-Regular.ttf", "NotoSans-Bold.ttf"];
for (const f of FONTS) total += cp(path.join(ROOT, "assets", "fonts", f), path.join(DIST, "vendor", "fonts", f));
if (existsSync(path.join(ROOT, "assets", "fonts", "Inter-LICENSE.txt"))) cp(path.join(ROOT, "assets", "fonts", "Inter-LICENSE.txt"), path.join(DIST, "vendor", "fonts", "Inter-LICENSE.txt"));

writeFileSync(path.join(DIST, "config.js"), `// generated by playground/build.mjs: self-contained layout
export const config = {
  mode: "dist",
  jsBase: "./vendor/",
  fontsBase: "./vendor/fonts/",
  wasm: { core: "bm_engine.core.wasm", standard: "bm_engine.standard.wasm", full: "bm_engine.wasm" },
  woffWasm: "bm_woff.wasm",
};
`);
console.log(`playground/dist ready (${(total / 1048576).toFixed(1)} MiB): ${path.relative(process.cwd(), DIST) || DIST}`);
