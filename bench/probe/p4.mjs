import { r, raw, px, row, font } from "./lib.mjs";
import { Renderer } from "@takumi-rs/wasm/node";
const n = {type:"container", style:{width:40,height:20, backgroundColor:"rgba(255,0,0,0.5)"}};
const png = await r.render(n, {width:40,height:20});
console.log("png sig", Buffer.from(png.slice(0,8)).toString("hex"), "IHDR bitdepth/colortype", png[24], png[25], "len", png.length);
const png2 = await r.render({type:"container", style:{width:40,height:20, backgroundImage:"linear-gradient(red,blue)"}}, {width:40,height:20});
console.log("png gradient colortype", png2[25]);
const big = await r.render({type:"container", style:{width:300,height:300, backgroundImage:"linear-gradient(red,blue), linear-gradient(to right, green, yellow)"}}, {width:300,height:300});
console.log("png manycolors colortype", big[25]);
const jpg = await r.render(n, {width:40,height:20, format:"jpeg"});
console.log("jpeg head", Buffer.from(jpg.slice(0,4)).toString("hex"), "len", jpg.length);
const jpgq = await r.render(n, {width:40,height:20, format:"jpeg", quality: 75});
console.log("jpeg q75 same as default", Buffer.compare(Buffer.from(jpg), Buffer.from(jpgq))===0);
const webp = await r.render(n, {width:40,height:20, format:"webp"});
console.log("webp", Buffer.from(webp.slice(0,16)).toString("latin1"));
const webpq = await r.render(n, {width:40,height:20, format:"webp", quality: 50});
console.log("webp q50", Buffer.from(webpq.slice(12,16)).toString("latin1"));
const ico = await r.render(n, {width:40,height:20, format:"ico"});
console.log("ico", Buffer.from(ico.slice(0,8)).toString("hex"));
const du = await r.renderAsDataUrl(n, {width:4,height:4});
console.log("dataurl", du.slice(0,40));
console.log("Renderer proto", Object.getOwnPropertyNames(Renderer.prototype).join(","));
const fams = await r.registerFont({name:"Inter", data: font("inter/inter-latin-opsz-wght-normal.woff2")});
console.log("registered", JSON.stringify(fams));
const fams2 = await r.registerFont(font("ubuntu/Ubuntu.ttc"));
console.log("registered ttc", JSON.stringify(fams2).slice(0,300));
