// Generator for src/font/color_emoji_tables.zig (emoji property range tables).
//
// Usage (from D:\project\bm-engine\bench):
//   curl -o <dir>/emoji-data.txt https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt
//   node probe/colorfont/gen_emoji_tables.mjs <dir>/emoji-data.txt ../src/font/color_emoji_tables.zig
//
// Each property becomes a sorted array of packed u32 ranges: (start << 11) | (len - 1), len <= 2048
// (longer ranges are split). Adjacent/overlapping ranges are merged. Lookup = binary search.
import { readFileSync, writeFileSync } from "node:fs";

const [src, out] = process.argv.slice(2);
if (!src || !out) { console.error("usage: gen_emoji_tables.mjs emoji-data.txt out.zig"); process.exit(1); }
const text = readFileSync(src, "utf8");
const version = (text.match(/^# emoji-data-([\d.]+)\.txt/m) || text.match(/Version:?\s*([\d.]+)/) || [, "?"])[1];
const props = { Emoji: [], Emoji_Presentation: [], Extended_Pictographic: [] };
for (const line of text.split("\n")) {
  const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/);
  if (!m || !(m[3] in props)) continue;
  const a = parseInt(m[1], 16), b = m[2] ? parseInt(m[2], 16) : a;
  props[m[3]].push([a, b]);
}
function pack(ranges) {
  ranges.sort((x, y) => x[0] - y[0]);
  const merged = [];
  for (const [a, b] of ranges) {
    const l = merged[merged.length - 1];
    if (l && a <= l[1] + 1) l[1] = Math.max(l[1], b); else merged.push([a, b]);
  }
  const outv = [];
  for (let [a, b] of merged) {
    while (b - a + 1 > 2048) { outv.push((a << 11 | 2047) >>> 0); a += 2048; }
    outv.push((a << 11 | (b - a)) >>> 0);
  }
  return outv;
}
const names = { Emoji: "emoji", Emoji_Presentation: "emoji_presentation", Extended_Pictographic: "extended_pictographic" };
let z = `//! GENERATED by bench/probe/colorfont/gen_emoji_tables.mjs from Unicode emoji-data.txt ${version}.\n` +
  `//! Do not edit. Each entry packs a code point range as (start << 11) | (len - 1).\n\n`;
let total = 0;
for (const [p, ranges] of Object.entries(props)) {
  const v = pack(ranges);
  total += v.length;
  z += `/// ${p} (${v.length} ranges)\npub const ${names[p]} = [_]u32{\n`;
  for (let i = 0; i < v.length; i += 8) z += "    " + v.slice(i, i + 8).map((x) => "0x" + x.toString(16).padStart(8, "0")).join(", ") + ",\n";
  z += "};\n\n";
}
writeFileSync(out, z.trimEnd() + "\n");
console.log(`unicode ${version}: wrote ${total} ranges (${total * 4} bytes) to ${out}`);
