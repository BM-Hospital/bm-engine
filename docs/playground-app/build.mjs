// Builds a self-contained, static copy of the playground (no build tools, only file copies):
//   node docs/playground-app/build.mjs                         -> docs/playground-app/dist/
//   node docs/playground-app/build.mjs --out ../public/playground-app   (relative to this folder; used by `npm run docs:build`)
// Copies the playground sources + js/*.mjs (browser entry points, incl. engine.mjs, pdf.mjs, pdf-api.mjs) + js/*.wasm
// (incl. bm_engine.pdf.wasm) + the default fonts into <out>/vendor/, the vendored pdf.js (third_party/pdfjs-<version>/)
// into <out>/vendor/pdfjs-<version>/, and writes <out>/config.js pointing at them, with the content hash of every wasm
// file (fetched as <file>?v=<hash>, which vercel.json caches for a year). Needs the prebuilt js/*.wasm (tracked in
// git) - no Zig. Nothing here is loaded up front except what Image mode needs: pdf.mjs, the pdf wasm and pdf.js are
// imported by app.js only when PDF mode (or its pdf.js preview) is used.
import { mkdirSync, rmSync, copyFileSync, writeFileSync, readdirSync, readFileSync, existsSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..", "..");
const argv = process.argv.slice(2);
const oi = argv.findIndex((a) => a === "--out" || a.startsWith("--out="));
const outArg = oi < 0 ? null : argv[oi].includes("=") ? argv[oi].slice(6) : argv[oi + 1];
const DIST = outArg ? path.resolve(HERE, outArg) : path.join(HERE, "dist");
if (DIST === HERE || DIST === ROOT || !DIST.startsWith(ROOT + path.sep)) { console.error(`refusing to write to ${DIST}`); process.exit(1); }
rmSync(DIST, { recursive: true, force: true });
mkdirSync(path.join(DIST, "vendor", "fonts"), { recursive: true });

const cp = (from, to) => { copyFileSync(from, to); return statSync(to).size; };
const sizes = {}; // group -> bytes
const add = (group, n) => { sizes[group] = (sizes[group] || 0) + n; };
for (const f of ["index.html", "style.css", "app.js", "i18n.js", "templates.js", "pdf-options.js", "pdf-templates.js"]) add("app", cp(path.join(HERE, f), path.join(DIST, f)));
const wasm = readdirSync(path.join(ROOT, "js")).filter((f) => f.endsWith(".wasm"));
if (wasm.length < 4) { console.error("js/*.wasm missing - build the engine first (node scripts/build.mjs)"); process.exit(1); }
if (!wasm.includes("bm_engine.pdf.wasm") || !existsSync(path.join(ROOT, "js", "pdf.mjs"))) { console.error("js/pdf.mjs or js/bm_engine.pdf.wasm missing (PDF mode needs them)"); process.exit(1); }
const versions = {};
for (const f of readdirSync(path.join(ROOT, "js"))) {
  if (!/\.(mjs|wasm)$/.test(f) || /^node(-|\.)/.test(f)) continue;
  const n = cp(path.join(ROOT, "js", f), path.join(DIST, "vendor", f));
  if (f.endsWith(".wasm")) {
    versions[f] = createHash("sha256").update(readFileSync(path.join(ROOT, "js", f))).digest("hex").slice(0, 12);
    add(f === "bm_engine.pdf.wasm" ? "pdf wasm (PDF mode only)" : "image wasm (one profile per page) + woff add-on", n);
  } else add(/^pdf(-api)?\.mjs$/.test(f) ? "pdf entry (PDF mode only)" : "engine js", n);
}
const FONTS = ["Inter-Regular.ttf", "Inter-SemiBold.ttf", "Inter-Bold.ttf", "Inter-Italic.ttf", "NotoSans-Regular.ttf", "NotoSans-Bold.ttf"];
for (const f of FONTS) add("fonts", cp(path.join(ROOT, "assets", "fonts", f), path.join(DIST, "vendor", "fonts", f)));
if (existsSync(path.join(ROOT, "assets", "fonts", "Inter-LICENSE.txt"))) cp(path.join(ROOT, "assets", "fonts", "Inter-LICENSE.txt"), path.join(DIST, "vendor", "fonts", "Inter-LICENSE.txt"));
// pdf.js: the PDF preview where the browser has no built-in viewer (phones) or when chosen
const pdfjsDir = readdirSync(path.join(HERE, "third_party")).find((d) => /^pdfjs-\d/.test(d));
if (!pdfjsDir) { console.error("docs/playground-app/third_party/pdfjs-<version>/ missing"); process.exit(1); }
mkdirSync(path.join(DIST, "vendor", pdfjsDir), { recursive: true });
for (const f of readdirSync(path.join(HERE, "third_party", pdfjsDir))) add("pdf.js (pdf.js preview only)", cp(path.join(HERE, "third_party", pdfjsDir, f), path.join(DIST, "vendor", pdfjsDir, f)));

writeFileSync(path.join(DIST, "config.js"), `// generated by docs/playground-app/build.mjs: self-contained layout
export const config = {
  mode: "dist",
  jsBase: "./vendor/",
  fontsBase: "./vendor/fonts/",
  wasm: { core: "bm_engine.core.wasm", standard: "bm_engine.standard.wasm", full: "bm_engine.wasm", pdf: "bm_engine.pdf.wasm" },
  woffWasm: "bm_woff.wasm",
  pdfjsBase: "./vendor/${pdfjsDir}/",
  versions: ${JSON.stringify(versions)},
};
`);
const total = Object.values(sizes).reduce((a, b) => a + b, 0);
const mib = (n) => (n >= 104858 ? (n / 1048576).toFixed(2) + " MiB" : (n / 1024).toFixed(1) + " KiB");
console.log(`playground build ready (${mib(total)}): ${path.relative(process.cwd(), DIST) || DIST}`);
for (const [g, n] of Object.entries(sizes)) console.log(`  ${g.padEnd(48)} ${mib(n).padStart(10)}`);
