// Generator for src/font/case_data.zig: compact Unicode case-mapping tables (full, locale-neutral
// uppercase incl. SpecialCasing expansions such as U+00DF -> "SS"; simple lowercase as the inverse of
// the uppercase runs plus a short list of exceptions).
//
//   node src/font/gen/gen_case.mjs [out = src/font/case_data.zig]
//
// The data comes from the ICU built into Node (String.prototype.toUpperCase / toLowerCase, which
// implement UnicodeData + SpecialCasing without locale tailoring); the Unicode version is recorded
// in the output header. Not run by the build: the output is checked in.
import { writeFileSync } from "node:fs";
const out = process.argv[2] ?? "src/font/case_data.zig";

// Runs of code points mapping with one constant delta, either every code point (stride 1) or every
// other one (stride 2: the Latin Extended / Cyrillic "pair" blocks). Packed u32 per run:
//   start (21 bits) << 11 | (count - 1) (10 bits) << 1 | stride-2 flag, plus an i32 delta.
function runs(map) {
  const cps = [...map.keys()].sort((a, b) => a - b);
  const res = [];
  let i = 0;
  while (i < cps.length) {
    const s = cps[i], d = map.get(s) - s;
    let n1 = 1; while (i + n1 < cps.length && cps[i + n1] === s + n1 && map.get(cps[i + n1]) - cps[i + n1] === d && n1 < 1024) n1++;
    let n2 = 1; while (n2 < 1024 && map.has(s + 2 * n2) && map.get(s + 2 * n2) - (s + 2 * n2) === d && !map.has(s + 2 * n2 - 1)) n2++;
    if (n2 > n1) { res.push({ s, n: n2, stride: 2, d }); i = cps.indexOf(s + 2 * (n2 - 1)) + 1; }
    else { res.push({ s, n: n1, stride: 1, d }); i += n1; }
  }
  return res;
}
const upper = new Map(), lower = new Map(), special = [];
for (let c = 0; c < 0x110000; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  const s = String.fromCodePoint(c);
  const u = [...s.toUpperCase()].map((x) => x.codePointAt(0));
  if (u.length === 1 && u[0] !== c) upper.set(c, u[0]);
  else if (u.length > 1) special.push([c, ...u]);
  const l = [...s.toLowerCase()].map((x) => x.codePointAt(0));
  if (l.length === 1 && l[0] !== c) lower.set(c, l[0]);
}
if (special.some((x) => x.length > 4 || x.some((v) => v > 0xffff))) throw new Error("special uppercase: BMP, at most 3");
const ur = runs(upper);
// lowercase = inverse of the uppercase runs (the first run, in start order, whose image holds the
// code point and whose source is not excluded), plus explicit pairs where that is wrong
const inRun = (r, src) => src >= r.s && src < r.s + r.n * r.stride && (src - r.s) % r.stride === 0;
const exclude = new Set();
for (const [src, up] of upper) if (lower.get(up) !== undefined && lower.get(up) !== src) exclude.add(src);
const inverse = (cp) => { for (const r of ur) { const src = cp - r.d; if (inRun(r, src) && !exclude.has(src)) return src; } return cp; };
const extra = [];
for (let c = 0; c < 0x110000; c++) { const want = lower.get(c) ?? c; if (inverse(c) !== want) extra.push([c, want]); }
const pack = (r) => `.{ 0x${((r.s << 11) | ((r.n - 1) << 1) | (r.stride === 2 ? 1 : 0)).toString(16)}, ${r.d} }`;
const hex = (v) => "0x" + v.toString(16);
const lines = [];
lines.push(`//! GENERATED by src/font/gen/gen_case.mjs from Unicode ${process.versions.unicode} (Node ${process.version} ICU ${process.versions.icu}). Do not edit.`);
lines.push(`//! Case mapping runs: .{ start << 11 | (count - 1) << 1 | stride2, delta } sorted by start.`);
lines.push(``);
lines.push(`/// Simple (1:1) uppercase mappings (${upper.size} code points, ${ur.length} runs).`);
lines.push(`pub const upper = [_]struct { u32, i32 }{\n    ${ur.map(pack).join(", ")},\n};`);
lines.push(`/// Sources skipped when inverting \`upper\` for lowercase (several characters uppercase to one).`);
lines.push(`pub const lower_exclude = [_]u32{ ${[...exclude].sort((a, b) => a - b).map(hex).join(", ")} };`);
lines.push(`/// Lowercase pairs the inverted runs get wrong (code point, lowercase).`);
lines.push(`pub const lower_extra = [_][2]u32{ ${extra.map((x) => `.{ ${hex(x[0])}, ${hex(x[1])} }`).join(", ")} };`);
lines.push(`/// Uppercase expansions (SpecialCasing, unconditional; all BMP): code point, then up to 3 code points (0 = none).`);
lines.push(`pub const upper_special = [_][4]u16{\n    ${special.map((x) => `.{ ${[...x, 0, 0, 0].slice(0, 4).map(hex).join(", ")} }`).join(", ")},\n};`);
writeFileSync(out, lines.join("\n") + "\n");
console.log(`upper ${upper.size} cps / ${ur.length} runs, lower ${lower.size} (exclude ${exclude.size}, extra ${extra.length}), special ${special.length}`);
