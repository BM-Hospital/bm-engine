fn lookup(table: []const Pair, c: u21) u21 {
    var lo: usize = 0;
    var hi = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (table[mid][0] < c) lo = mid + 1 else hi = mid;
    }
    return if (lo < table.len and table[lo][0] == c) table[lo][1] else c;
}
pub fn fullWidth(c: u21) u21 {
    return lookup(&full_width, c);
}
pub fn fullSizeKana(c: u21) u21 {
    return lookup(&full_size_kana, c);
}
